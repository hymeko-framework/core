<#
.SYNOPSIS
    Produce an offline vendor tree and the matching cargo source-replacement
    config for this workspace.

.DESCRIPTION
    The workspace builds offline on the original development host because a
    pre-populated `vendor/` directory sits NEXT TO the repository and a
    `.cargo/config.toml` in that parent directory redirects crates.io to it.

    Neither of those is part of this repository:

      * the parent directory is not a git repository at all;
      * the vendor tree is ~564 MB across ~334 crates;
      * the config hardcodes an absolute path from one machine.

    So a fresh clone cannot build offline until an equivalent tree is created.
    This script creates one, from the checksums already pinned in `Cargo.lock`.

    ONLINE BUILDS NEED NONE OF THIS. `Cargo.lock` carries a checksum for every
    registry crate, so `cargo build` reproduces the exact dependency set from
    crates.io directly. The vendor tree is purely an offline convenience.

.PARAMETER TargetDir
    Where to write the vendor tree. Relative paths are resolved against the
    repository root. Defaults to `../vendor`, matching the original layout, but
    nothing depends on that choice.

.PARAMETER ConfigOut
    Where to write the generated cargo config. Defaults to `.cargo/config.toml`
    inside the repository, which keeps the checkout self-contained.

.EXAMPLE
    ./scripts/dev/prepare_offline_vendor.ps1
    # vendor at ../vendor, config at ./.cargo/config.toml

.EXAMPLE
    ./scripts/dev/prepare_offline_vendor.ps1 -TargetDir vendor -ConfigOut .cargo/config.toml
    # fully self-contained checkout

.NOTES
    Requires network access ONCE, to populate the tree. After that the workspace
    builds with `--offline`.

    The git dependency (`parser`, pinned in Cargo.lock to commit e28a205) is NOT
    vendored by `cargo vendor` in a form that works offline without also having
    that repository reachable; fetch it while online, or add it as a path
    override. This is stated rather than silently handled, because a script that
    pretended otherwise would produce a tree that fails at the worst moment.
#>
[CmdletBinding()]
param(
    [string]$TargetDir = '../vendor',
    [string]$ConfigOut = '.cargo/config.toml'
)

$ErrorActionPreference = 'Stop'
$repoRoot = (& git rev-parse --show-toplevel).Trim()
if (-not $repoRoot) { throw 'not inside a git repository' }
Push-Location $repoRoot
try {
    # Resolve relative to the repo root, never to the caller's cwd, so the
    # script behaves the same however it is invoked.
    $vendorPath = if ([System.IO.Path]::IsPathRooted($TargetDir)) {
        $TargetDir
    } else {
        Join-Path $repoRoot $TargetDir
    }
    $configPath = if ([System.IO.Path]::IsPathRooted($ConfigOut)) {
        $ConfigOut
    } else {
        Join-Path $repoRoot $ConfigOut
    }

    Write-Host "repo root : $repoRoot"
    Write-Host "vendor to : $vendorPath"
    Write-Host "config to : $configPath"

    if (Test-Path $vendorPath) {
        $existing = @(Get-ChildItem -Path $vendorPath -Directory -ErrorAction SilentlyContinue).Count
        if ($existing -gt 0) {
            throw "refusing to overwrite: '$vendorPath' already contains $existing crate directories. Remove it or pass -TargetDir."
        }
    }

    # `cargo vendor` prints the config stanza it wants on stdout. Capture it
    # rather than hand-writing one, so the format cannot drift from cargo's.
    Write-Host 'running cargo vendor (needs network) ...' -ForegroundColor Cyan
    $prevEap = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    $stanza = & cargo vendor --versioned-dirs $vendorPath 2>&1
    $code = $LASTEXITCODE
    $ErrorActionPreference = $prevEap
    if ($code -ne 0) {
        $stanza | ForEach-Object { Write-Host $_ }
        throw "cargo vendor failed with exit code $code"
    }

    # Keep only the config stanza; cargo interleaves progress on stderr.
    $lines = @($stanza | Where-Object { $_ -notmatch '^\s*(Downloaded|Downloading|Compiling|\s*Updating|Vendoring)' })

    $dir = Split-Path -Parent $configPath
    if ($dir -and -not (Test-Path $dir)) { New-Item -ItemType Directory -Force $dir | Out-Null }

    $header = @(
        '# Generated by scripts/dev/prepare_offline_vendor.ps1.',
        '#',
        '# Offline source replacement for this workspace. The path below is',
        '# written relative to this file where possible; if it is absolute, it is',
        '# machine-specific and should NOT be committed.',
        ''
    )
    ($header + $lines) | Set-Content -Path $configPath -Encoding utf8

    Write-Host ''
    Write-Host "wrote $configPath" -ForegroundColor Green
    Write-Host 'verify with:  cargo check --workspace --offline'
    Write-Host ''
    Write-Warning 'If the generated config contains an ABSOLUTE path, do not commit it. Add it to .gitignore or rewrite the path as relative.'
}
finally {
    Pop-Location
}
